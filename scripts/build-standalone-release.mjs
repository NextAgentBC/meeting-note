import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const publicDir = join(root, "public");
const generated = join(root, "src", "standalone-assets.generated.ts");
const releaseDir = join(root, "installer", "public", "release");
let releaseVersion = process.env.RELEASE_VERSION;
if (!releaseVersion) {
  try {
    releaseVersion = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
  } catch {
    releaseVersion = "dev";
  }
}

const MIME = {
  ".css": "text/css; charset=utf-8", ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8", ".json": "application/json; charset=utf-8",
  ".png": "image/png", ".svg": "image/svg+xml", ".wasm": "application/wasm",
  ".webmanifest": "application/manifest+json"
};
const binary = new Set([".png", ".wasm"]);

function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? files(path) : [path];
  });
}

const assets = Object.fromEntries(files(publicDir).map((path) => {
  const pathname = `/${relative(publicDir, path).replaceAll("\\", "/")}`;
  const extension = extname(path);
  const contents = readFileSync(path);
  return [pathname, {
    type: MIME[extension] || "application/octet-stream",
    body: binary.has(extension) ? contents.toString("base64") : contents.toString("utf8"),
    binary: binary.has(extension)
  }];
}));

writeFileSync(generated, `// Generated by scripts/build-standalone-release.mjs. Do not edit.
const ASSETS = ${JSON.stringify(assets)};

function bytes(value: string): Uint8Array {
  const decoded = atob(value);
  return Uint8Array.from(decoded, (character) => character.charCodeAt(0));
}

export function serveEmbeddedAsset(request: Request): Response {
  const url = new URL(request.url);
  let path = url.pathname === "/" ? "/index.html" : url.pathname;
  let asset = ASSETS[path as keyof typeof ASSETS];
  if (!asset && !path.includes(".")) asset = ASSETS["/index.html"];
  if (!asset) return new Response("Not found", { status: 404 });
  return new Response(asset.binary ? bytes(asset.body).buffer as ArrayBuffer : asset.body, {
    headers: {
      "content-type": asset.type,
      "cache-control": path === "/service-worker.js" ? "no-cache" : "public, max-age=0, must-revalidate",
      "x-content-type-options": "nosniff"
    }
  });
}
`);

// Split on semicolons, but not the ones inside a trigger body: CREATE TRIGGER … BEGIN … END;
// The D1 binding runs one statement per prepare(), so the split happens here, once, at build time.
function statements(sql) {
  const found = [];
  let current = "";
  let depth = 0;
  let quote = "";
  for (let index = 0; index < sql.length; index += 1) {
    const character = sql[index];
    current += character;
    if (quote) {
      if (character === quote) quote = "";
      continue;
    }
    if (character === "'" || character === '"') { quote = character; continue; }
    if (character === "-" && sql[index + 1] === "-") {
      const end = sql.indexOf("\n", index);
      const comment = end === -1 ? sql.slice(index) : sql.slice(index, end);
      current += comment.slice(1);
      index += comment.length - 1;
      continue;
    }
    const ahead = sql.slice(index).toUpperCase();
    if (/^\bBEGIN\b/.test(ahead)) depth += 1;
    else if (/^\bEND\b/.test(ahead) && depth > 0) depth -= 1;
    if (character === ";" && depth === 0) {
      const statement = current.trim();
      if (statement.replace(/;$/, "").trim()) found.push(statement.replace(/;$/, "").trim());
      current = "";
    }
  }
  const tail = current.trim();
  if (tail) found.push(tail);
  return found;
}

// What proves this migration has already run, for a copy installed before migrations were tracked.
function sentinel(sql) {
  const candidates = [
    [/CREATE\s+(?:VIRTUAL\s+)?TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_]\w*)/i, (match) => ({ kind: "table", name: match[1] })],
    [/ALTER\s+TABLE\s+([A-Za-z_]\w*)\s+ADD\s+COLUMN\s+([A-Za-z_]\w*)/i, (match) => ({ kind: "column", name: match[1], column: match[2] })],
    [/CREATE\s+(?:UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_]\w*)/i, (match) => ({ kind: "table", name: match[1] })]
  ];
  let best = null;
  for (const [pattern, build] of candidates) {
    const match = sql.match(pattern);
    if (match && (best === null || match.index < best.index)) best = { index: match.index, value: build(match) };
  }
  return best ? best.value : null;
}

const migrations = files(join(root, "migrations"))
  .filter((path) => path.endsWith(".sql"))
  .sort()
  .map((path) => {
    const name = relative(join(root, "migrations"), path);
    const sql = readFileSync(path, "utf8");
    // PRAGMA is a connection setting, not schema, and D1 rejects it inside a transaction.
    return { name, sql, statements: statements(sql).filter((statement) => !/^PRAGMA\b/i.test(statement)), sentinel: sentinel(sql) };
  });
mkdirSync(releaseDir, { recursive: true });
writeFileSync(join(releaseDir, "migrations.json"), JSON.stringify({
  version: releaseVersion,
  migrations: migrations.map(({ name, sql }) => ({ name, sql }))
}));

// The app carries its own schema, so a copy that is updated in place brings its database with it.
writeFileSync(join(root, "src", "migrations.generated.ts"), `// Generated by scripts/build-standalone-release.mjs. Do not edit.
export const RELEASE_VERSION = ${JSON.stringify(releaseVersion)};

export type MigrationSentinel = { kind: "table"; name: string } | { kind: "column"; name: string; column: string };
export type Migration = { name: string; statements: string[]; sentinel: MigrationSentinel | null };

export const MIGRATIONS: Migration[] = ${JSON.stringify(migrations.map(({ name, statements, sentinel }) => ({ name, statements, sentinel })), null, 2)};
`);

// Bundle last: the Worker imports RELEASE_VERSION from the file written just above, and an installed
// copy reports it from /api/health. Bundled before that file was rewritten (as it was until
// 2026-09-25), every release carried the previous release's version, so an up-to-date copy kept
// offering an update. Refuse to publish a bundle that does not carry the version it is released as.
execFileSync("npx", ["wrangler", "deploy", "--dry-run", "--config", "wrangler.standalone.jsonc", "--outdir", releaseDir], {
  cwd: root,
  stdio: "inherit"
});
const bundled = readFileSync(join(releaseDir, "standalone.js"), "utf8");
if (!bundled.includes(`RELEASE_VERSION = ${JSON.stringify(releaseVersion)}`)) {
  throw new Error(`installer/public/release/standalone.js does not carry release ${releaseVersion}`);
}
